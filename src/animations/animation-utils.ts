export function getObjectElementById(id: string): HTMLDivElement {
  const el = document.getElementsByClassName(
    `object-${id}`
  )[0] as HTMLDivElement;
  return el;
}

export function getLayerElementById(id: string): HTMLDivElement {
  const el = document.getElementsByClassName(
    `layer-${id}`
  )[0] as HTMLDivElement;
  return el;
}

// used for all tiles animations
export function getParameters(
  rows: number,
  columns: number,
  startFrom: string
) {
  switch (startFrom) {
    case "random":
      return { stagger: { from: "random" } };
    case "center":
      return {
        stagger: {
          from: "center",
        },
      };
    case "horizontal-center":
      return {
        stagger: {
          from: "center",
          axis: "y",
        },
      };
    case "vertical-center":
      return {
        stagger: {
          from: "center",
          axis: "x",
        },
      };
    case "edges":
      return { stagger: { from: "edges" } };
    case "horizontal-edges":
      return {
        stagger: {
          from: "edges",
          axis: "y",
        },
      };
    case "vertical-edges":
      return {
        stagger: {
          from: "edges",
          axis: "x",
        },
      };
    case "top-left":
      return {
        stagger: {
          from: "0",
        },
      };
    case "top-right":
      return {
        stagger: {
          from: `${columns - 1}`,
        },
      };
    case "bottom-left":
      return {
        stagger: {
          from: `${columns * (rows - 1)}`,
        },
      };
    case "bottom-right":
      return {
        stagger: {
          from: `${columns * rows - 1}`,
        },
      };
  }
}
